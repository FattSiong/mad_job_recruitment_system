/// A skill on the job seeker's profile ("Skill" table).
class SkillModel {
  static const List<String> proficiencyLevels = ['Beginner', 'Intermediate', 'Advanced'];

  final String? skillID;
  final String seekerID;
  final String skillName;
  final String? proficiency; // 'Beginner' | 'Intermediate' | 'Advanced' | null
  final DateTime? createdAt;

  SkillModel({
    this.skillID,
    required this.seekerID,
    required this.skillName,
    this.proficiency,
    this.createdAt,
  });

  factory SkillModel.fromJson(Map<String, dynamic> json) {
    return SkillModel(
      skillID: json['skillID'] as String?,
      seekerID: json['seekerID'] as String,
      skillName: json['skillName'] as String,
      proficiency: json['proficiency'] as String?,
      createdAt: json['createdAt'] != null ? DateTime.tryParse(json['createdAt'] as String) : null,
    );
  }

  /// skillID and createdAt are generated by the database.
  Map<String, dynamic> toJson() {
    return {
      'seekerID': seekerID,
      'skillName': skillName,
      'proficiency': proficiency,
    };
  }
}
